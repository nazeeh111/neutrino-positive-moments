"""Sufficient general 3D moment exclusion on an exact parameterized domain.

No completeness, astrophysical utility, runtime advantage or priority claim.
Inputs are exact Fractions; frequency is generated by rational a,b,h,t.
"""
from fractions import Fraction as F
from pathlib import Path
import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from independent_verifier import C
from exact_nonaxial_imaginary_bound import positive


def require(ok, message):
    if not ok:
        raise ValueError(message)


def moments(atoms):
    return {'N': sum((w for v, w in atoms), F(0)),
            'F': [sum((w*v[i] for v, w in atoms), F(0)) for i in range(3)],
            'Q': [[sum((w*v[i]*v[j] for v, w in atoms), F(0)) for j in range(3)] for i in range(3)]}


def validate(m):
    N, f, q = m['N'], m['F'], m['Q']
    require(isinstance(N, F) and len(f) == 3 and len(q) == 3 and all(len(row) == 3 for row in q),
            'Expected exact scalar/vector/tensor moments')
    require(all(isinstance(v, F) for v in f) and all(isinstance(v, F) for row in q for v in row),
            'Expected Fraction entries')
    require(q == [list(row) for row in zip(*q)] and sum(q[i][i] for i in range(3)) == N,
            'Tensor must be symmetric and have trace N')
    gram = [[N, *f]]+[[f[i], *q[i]] for i in range(3)]
    require(positive(gram), 'Moment Gram matrix is not positive semidefinite')


def mean_Q(m, a, b, h, t, reflected=False):
    N, f, q = m['N'], m['F'], m['Q']
    f = [-v for v in f] if reflected else f
    K = b*h+a*t
    e, alpha, beta = (K*K-t*t)/(h*h), b*(1+2*t*t)/h, -t/h
    out = [[F(0) for _ in range(3)] for _ in range(3)]
    out[0][0] = F(3, 2)*(N-q[2][2])
    for i in range(2):
        out[0][i+1] = out[i+1][0] = F(3, 2)*(alpha*f[i]+beta*q[2][i])
        for j in range(2):
            out[i+1][j+1] = F(3, 2)*((K*K*q[2][2]/(h*h) if i == j else 0)+e*q[i][j])
    return out


def evaluate(plus, minus, k, a, b, h, t):
    for m in (plus, minus):
        validate(m)
    require(all(isinstance(v, F) for v in (k, a, b, h, t)), 'Exact parameters required')
    require(k > 0 and b > 0 and t > 0 and h > 0 and a*a+b*b == 1 and h*h-t*t == 1,
            'Invalid frequency parameterization')
    x, y = a*h, b*t
    omega, r = k*C(x, y), C(x, y)
    g0 = plus['N']-minus['N']
    g = [u-v for u, v in zip(plus['F'], minus['F'])]
    Omega, Kz = omega+g0, k+g[2]
    Delta = k*Kz-omega*Omega
    basic = {'omega': omega, 'k': k, 'Delta': Delta}
    if Delta == C():
        return {**basic, 'status': 'unresolved', 'reason': 'singular reduction Delta=0'}
    M0 = [[C() for _ in range(3)] for _ in range(3)]
    M0[0][0] = (k*Kz+g0*Omega)/Delta
    for i in range(2):
        M0[0][i+1] = M0[i+1][0] = Omega*g[i]/Delta
        for j in range(2):
            M0[i+1][j+1] = (-1 if i == j else 0)+g[i]*g[j]/Delta
    root = C(b*h, -a*t)
    require(root*root == 1-r*r, 'Square root identity failed')
    J = [C(0, 1)*root, C(1), C(1)]
    B0 = [[(-J[i]*M0[i][j]*J[j]).re for j in range(3)] for i in range(3)]
    B0[0][0] -= (x*g0+g[2])/k
    qp, qm = mean_Q(plus, a, b, h, t), mean_Q(minus, -a, b, h, t, reflected=True)
    lower = [[B0[i][j]-(qp[i][j]+qm[i][j])/(3*omega.im) for j in range(3)] for i in range(3)]
    return {**basic, 'status': 'excluded' if positive(lower, strict=True) else 'unresolved',
            'lower_matrix': lower, 'M0': M0, 'J': J, 'B0': B0}


def constant_rayleigh_squared(plus, minus):
    """Exact lower bound on ||cross-species kernel||², not an exclusion cap."""
    Np, Nm, fp, fm, qp = plus['N'], minus['N'], plus['F'], minus['F'], plus['Q']
    require(Nm > 0, 'Nonzero minus mass required')
    return Np*Nm-2*sum(x*y for x, y in zip(fp, fm))+sum(fm[i]*qp[i][j]*fm[j]
        for i in range(3) for j in range(3))/Nm
